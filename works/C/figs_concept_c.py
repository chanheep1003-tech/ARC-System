def wrap(t, w):
    return "\n".join(textwrap.fill(p, w, break_long_words=False, break_on_hyphens=False) for p in t.split("\n"))


def nd(title, body, qs, w, fs=6.6):
    return dict(title=title, body=wrap(body, w), qs=qs, fs=fs)


def pair(a, b):
    w = 31
    na = nd(*a, w=w); nb = nd(*b, w=w)
    return dict(kind="pair", h=fc.h_of(na["body"], nb["body"]), nodes=[na, nb])


def full(t, body, qs, fs=6.4):
    x = nd(t, body, qs, w=68, fs=fs)
    return dict(kind="full", h=fc.h_of(x["body"]), node=x)


