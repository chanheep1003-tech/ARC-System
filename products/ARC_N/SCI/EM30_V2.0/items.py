def table(head, rows, cls="dtab"):
    th = "".join(f"<th>{h}</th>" for h in head)
    trs = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="{cls}"><tr>{th}</tr>{trs}</table>'


def exp(title, lines):
    body = "".join(f'<div class="hang"><span>{a}</span><span>{b}</span></div>' if a else f"<div>{b}</div>"
                   for a, b in lines)
    return f'<div class="exp"><div class="exph">{title}</div>{body}</div>'


