def eqbox(rows):
    body = "".join(f'<tr><td class="eqk">{k}</td><td>{v}</td></tr>' for k, v in rows)
    return f'<table class="eqtab">{body}</table>'


def table(head, rows, cls="dtab"):
    th = "".join(f"<th>{h}</th>" for h in head)
    trs = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="{cls}"><tr>{th}</tr>{trs}</table>'


