from revise_a import REV
import re

def patch(n, idx, old, new):
    ch = REV[n]["choices"]
    assert old in ch[idx], (n, idx, old)
    ch[idx] = ch[idx].replace(old, new)

def plain(t): return re.sub(r"<[^>]+>", "", t)

