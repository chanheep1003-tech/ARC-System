def mcq(arch, topic, d, rules, units, levers, stem, view, options, answer, judg, neg=False, adv=False,
        reuse=False, set_id=None, steps=None):
    js = []
    for i, (claim, c, why, *trap) in enumerate(judg, 1):
        j = {"axis": "orthography", "c": "CORRECT" if i == answer else c, "claim": claim,
             "ev": ["VIEW", f"OPTION{i}"], "v": (i != answer) if neg else (i == answer), "why": why}
        if i != answer:
            j["trap"] = trap[0]
        js.append(j)
    strong = [i for i, (_, c, *_r) in enumerate(judg, 1) if i != answer and c == S]
    it = {"item_id": f"KOR-V6O2-{len(items) + 1:02d}", "archetype": arch, "topic": topic, "rules": rules,
          "judgment_units": units, "levers": levers, "textbook_example_reuse": reuse,
          "stem": stem, "view": view, "options": options, "answer": answer,
          "second_best": strong[0] if strong else (1 if answer != 1 else 2),
          "difficulty": d, "family": FAMILY[arch.split("_")[0]],
          "balance": "ADVANCED_DISCRIMINATION" if adv else "CORE_EXAM_POINT",
          "reasoning_steps": steps or len(levers) + 1, "immediate_elimination": 1 if d in ("D4", "D5") else 2,
          "transfer": True, "stem_polarity": "NEGATIVE" if neg else "POSITIVE"}
    if set_id:
        it["set_id"] = set_id
    it["judgments"] = js
    items.append(it)


